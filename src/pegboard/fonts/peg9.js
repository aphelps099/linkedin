// PEG-9 Heavy: the read-out face of the Peg Board. Capitals 9 rows tall, with
// 2 descender rows for the comma, semicolon and Q's tail.
//   Weight: 2-peg stems, 2-row top and bottom bars, 1-row crossbars on row 4 (the
//   lighter crossbar is the optical correction that keeps E, B and 8 open).
//   Widths: 6 for straight letters (2-peg counters, the heavy rhythm of stem,
//   counter, stem); 7 for the rounds O C G Q and the diagonals A N V X, whose
//   diagonals need a third counter column to stay 2 pegs thick; 7 for M and W;
//   5 for E F L, whose open sides would otherwise gape; I is 2.
//   Rounds cut their corners by one peg; the zero cuts by two, a narrow oval,
//   so 0 never reads as O or D. 1 carries a diagonal flag, never an I. 5 has a
//   square shoulder and no spur, S spurs and cut corners. 8 is round on both sides;
//   B is flat on the left with a smaller upper bowl, as in the classic grotesques.
//   A and V are drawn as triangles, so TA and AV kern themselves (see kern()).
// Tracking 1, word space 4, line gap 1 (12 rows from line to line).
