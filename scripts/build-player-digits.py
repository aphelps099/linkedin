"""Build the original, digits-only LinkedIn Beats LCD face. Requires fontTools."""
import base64
from io import BytesIO
from pathlib import Path
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen


def horizontal(y):
    return [(104, y), (396, y), (426, y + 30), (396, y + 60), (104, y + 60), (74, y + 30)]


def vertical(x, y):
    return [(x, y + 36), (x + 30, y + 6), (x + 60, y + 36), (x + 60, y + 294), (x + 30, y + 324), (x, y + 294)]


segments = {
    'a': horizontal(740), 'g': horizontal(370), 'd': horizontal(0),
    'f': vertical(25, 430), 'b': vertical(415, 430),
    'e': vertical(25, 60), 'c': vertical(415, 60),
}
digits = ['ab cdef'.replace(' ', ''), 'bc', 'abged', 'abgcd', 'fgbc', 'afgcd', 'afgecd', 'abc', 'abcdefg', 'abfgcd']
glyphs, metrics = {}, {}
for name, outlines, advance in [('.notdef', [], 540), ('space', [], 220)] + [
    (f'digit{i}', [segments[s] for s in letters], 540) for i, letters in enumerate(digits)
] + [('colon', [[(80, y), (130, y), (130, y + 50), (80, y + 50)] for y in (235, 515)], 220)]:
    pen = TTGlyphPen(None)
    for outline in outlines:
        pen.moveTo(outline[0])
        for point in outline[1:]:
            pen.lineTo(point)
        pen.closePath()
    glyphs[name] = pen.glyph()
    metrics[name] = (advance, 0)

font = FontBuilder(1000, isTTF=True)
font.setupGlyphOrder(list(glyphs))
font.setupCharacterMap({32: 'space', 58: 'colon', **{48+i: f'digit{i}' for i in range(10)}})
font.setupGlyf(glyphs)
font.setupHorizontalMetrics(metrics)
font.setupHorizontalHeader(ascent=900, descent=-100)
font.setupNameTable({'familyName': 'LB Digital', 'styleName': 'Regular', 'uniqueFontIdentifier': 'LinkedInBeats-LBDigital-1', 'fullName': 'LB Digital Regular', 'psName': 'LBDigital-Regular', 'version': 'Version 1.0'})
font.setupOS2(sTypoAscender=900, sTypoDescender=-100, usWinAscent=900, usWinDescent=100)
font.setupPost()
font.setupMaxp()
buffer = BytesIO()
font.save(buffer)
encoded = base64.b64encode(buffer.getvalue()).decode('ascii')
destination = Path(__file__).resolve().parents[1] / 'src/home-experiments/player-digits.css'
destination.write_text('/* Original LCD numerals; generated by scripts/build-player-digits.py. */\n'
    '@font-face{font-family:LBDigital;src:url("data:font/ttf;base64,' + encoded + '") format("truetype");'
    'font-weight:400;font-style:normal;font-display:swap;unicode-range:U+0030-0039,U+003A}\n')
print(f'{destination.name}: {destination.stat().st_size} bytes')
