"""Verify returned audio, encode delivery files, and write exact runtime bindings."""
import hashlib, json, subprocess
from pathlib import Path
import numpy as np
from scipy.io import wavfile
from scipy.signal import correlate, correlation_lags

ROOT=Path(__file__).resolve().parents[1]
DIR=ROOT/'assets/meeting-performances/standup-0'
OUT=ROOT/'public/studio/performances'
TASKS={
    'guitar':('ca9e2bb4-e9dd-4586-90f6-0c07f17bd1e4','915027c4-cfc2-4e50-9782-42c234ca9bc8'),
    'keys':('e1953b2e-0126-4e46-b827-bd54ba536a4e','b4373f48-de83-463b-b323-e48f049d2de5'),
    'operations':('3a6940ef-2fa2-4192-98b5-005e8d8704e5','f72dd0be-2553-402c-ac9f-e6850076855f'),
}
hook=json.loads((ROOT/'src/meeting-room/audio-manifest.json').read_text())['meetings']['standup-0']['cues'][7]
solos={}; chorus={'cueDuration':hook['duration'],'sources':hook['sources'],'performances':{}}
OUT.mkdir(parents=True,exist_ok=True)
for character,(task,asset) in TASKS.items():
    path=DIR/f'{character}.json'; job=json.loads(path.read_text())
    source=DIR/f'{character}-performance.mp4'
    _,x=wavfile.read(DIR/job['audio']);x=x.astype(float)
    data=subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-ac','1','-ar','24000','-f','s16le','-'])
    y=np.frombuffer(data,dtype='<i2').astype(float)
    corr=correlate(y,x); lag=int(correlation_lags(len(y),len(x))[np.argmax(corr)])
    n=min(len(x),len(y)); correlation=float(np.corrcoef(x[:n],y[:n])[0,1])
    assert lag==0 and correlation>.999, (character,lag,correlation)
    dest=OUT/f'{character}-standup-exact-v1.mp4'
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(source),'-vf',
        'scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2:color=0x111315,setsar=1',
        '-c:v','libx264','-preset','medium','-crf','20','-pix_fmt','yuv420p',
        '-c:a','copy','-movflags','+faststart',str(dest)],check=True)
    job.update(status='reviewed-integrated',taskId=task,assetId=asset,
        runwaySession='5bb35d14-ea57-4d00-979c-8d4c846ccbad',creditsSpent=2,
        output=source.name,outputSha256=hashlib.sha256(source.read_bytes()).hexdigest(),
        runtimeVideo=str(dest.relative_to(ROOT)),runtimeSha256=hashlib.sha256(dest.read_bytes()).hexdigest(),
        audioLagSeconds=0,audioWaveformCorrelation=correlation,
        reviewNotes='Reviewed solo and chorus frames: attached lips, stable face/headset, natural blinks and subtle head motion. Close speaking framing matches the approved Kevin pilot. Instruments remain in the inter-line footage. Original approved voice masters remain the live audio.')
    path.write_text(json.dumps(job,indent=2,ensure_ascii=False)+'\n')
    video='/'+str(dest.relative_to(ROOT/'public'))
    solo=job['solo']; take=solo['sources'][0]
    solos[take['take']]={'character':character,'masterSha256':take['masterSha256'],'video':video,'offset':solo['offset'],'duration':solo['duration']}
    chorus['performances'][character]={'character':character,'video':video,'offset':job['chorus']['offset'],'duration':job['chorus']['duration']}
    print(character,'audio correlation',round(correlation,7),'lag',lag,'runtime bytes',dest.stat().st_size)
target=ROOT/'src/meeting-room/standup-performances.js'
target.write_text('// Generated by scripts/package-standup-performances.py from reviewed exact audio performances.\n'
    +'export const standupSolos='+json.dumps(solos,separators=(',',':'))+';\n'
    +'export const standupChorus='+json.dumps(chorus,separators=(',',':'))+';\n')
