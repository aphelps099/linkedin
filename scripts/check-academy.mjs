import assert from 'node:assert/strict';
import {makeHook,cleanHookDraft} from '../src/program/arcade/hook.js';
import {loadProgress,saveProgress} from '../src/program/engine/progress.js';
assert.equal(makeHook('I made coffee.'),'I almost didn’t make coffee today.\n\nHere’s why that matters.');
assert.equal(makeHook('I sent an email yesterday.'),'I almost didn’t send an email yesterday.\n\nHere’s why that matters.');
assert.equal(makeHook('The printer worked!'),'The printer worked.\n\nAn ordinary update? That’s what I thought, too.');
assert.equal(cleanHookDraft(null),null);
assert.equal(cleanHookDraft({stage:'unknown',fact:'x'.repeat(600)}).fact.length,400);
assert.equal(cleanHookDraft({stage:'unknown'}).stage,'example');
let saved=JSON.stringify({userName:'Existing Learner',completedChapters:['inflation','shape'],posts:{single:'My final post'},currentChapter:3});
globalThis.localStorage={getItem:()=>saved,setItem:(_,value)=>{saved=value;}};
const previous=loadProgress();
const draft={stage:'practice',fact:'I sent an email.',post:'My edited hook.',tried:true};
saveProgress({lessonDrafts:{hook:draft}},previous);
const restored=loadProgress();
assert.deepEqual(restored.lessonDrafts.hook,draft);
assert.equal(restored.userName,'Existing Learner');
assert.deepEqual(restored.completedChapters,['inflation','shape']);
assert.equal(restored.posts.single,'My final post');
assert.equal(restored.currentChapter,3);
globalThis.localStorage={getItem:()=>'{broken',setItem:()=>{throw Error('blocked');}};
assert.deepEqual(loadProgress().lessonDrafts,{});
assert.equal(saveProgress({lessonDrafts:{hook:draft}}).lessonDrafts.hook.post,'My edited hook.');
console.log('OK academy: hook scaffolds, draft validation, resume, existing progress, unavailable storage');
