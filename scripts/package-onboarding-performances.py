"""Validate approved audio preservation and bind reviewed onboarding performances."""
import hashlib,json,subprocess
from pathlib import Path
import numpy as np
from scipy.io import wavfile
from scipy.signal import correlate,correlation_lags
ROOT=Path(__file__).resolve().parents[1]
DIR=ROOT/'assets/meeting-performances/onboarding-0';OUT=ROOT/'public/studio/performances'
TASKS={
 'people':('71ecc52c-5a99-4d1a-9603-ef6a4adce77c','07c28229-2c26-42cb-a890-fb7c5fb3a700'),
 'keys':('d8d9dd7e-fa8f-4a12-ad0b-904e859c893d','7cdf4181-93f2-4e17-b0cd-05be5f799504'),
 'strategy':('ac4f6e3d-3a44-4f74-accb-04a7a817bd40','1229a830-ad8c-4d6f-a3b9-057756b56863'),
 'guitar':('d74c461c-8a13-4ad6-8f7b-65a597ce1f80','b8331c2f-2ae1-455b-8297-a7db16a13543'),
 'operations':('44baa5b5-fde8-4db9-bc4a-e6ea57e3e319','e8659501-9e44-4048-bb3b-3f50cafb82be'),
}
hook=json.loads((ROOT/'src/meeting-room/audio-manifest.json').read_text())['meetings']['onboarding-0']['cues'][7]
solos={};chorus={'cueDuration':hook['duration'],'sources':hook['sources'],'performances':{}}
for character,(task,asset) in TASKS.items():
    path=DIR/f'{character}.json';job=json.loads(path.read_text());source=DIR/f'{character}-performance.mp4'
    _,x=wavfile.read(DIR/job['audio']);x=x.astype(float)
    data=subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-ac','1','-ar','24000','-f','s16le','-'])
    y=np.frombuffer(data,dtype='<i2').astype(float)
    lag=int(correlation_lags(len(y),len(x))[np.argmax(correlate(y,x))]);n=min(len(x),len(y))
    correlation=float(np.corrcoef(x[:n],y[:n])[0,1]);assert lag==0 and correlation>.999,(character,lag,correlation)
    dest=OUT/f'{character}-onboarding-exact-v1.mp4'
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(source),'-vf',
        'scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2:color=0x111315,setsar=1',
        '-c:v','libx264','-preset','medium','-crf','20','-pix_fmt','yuv420p','-c:a','copy','-movflags','+faststart',str(dest)],check=True)
    job.update(status='reviewed-integrated',taskId=task,assetId=asset,creditsSpent=2,
        runwaySession='5bb35d14-ea57-4d00-979c-8d4c846ccbad',output=source.name,
        outputSha256=hashlib.sha256(source.read_bytes()).hexdigest(),runtimeVideo=str(dest.relative_to(ROOT)),
        runtimeSha256=hashlib.sha256(dest.read_bytes()).hexdigest(),audioLagSeconds=0,audioWaveformCorrelation=correlation,
        reviewNotes='Reviewed solo and chorus frames: stable face/headset, attached lips, subtle blinks. Original approved voice master stays in the live meeting. Keys has a separate approved keyboard camera during speech because the speech renderer reframes to a close shot.')
    if character=='keys':job['characterImage']='assets/meeting-performances/onboarding-0/keys-wide-reference.png'
    path.write_text(json.dumps(job,indent=2,ensure_ascii=False)+'\n')
    video='/'+str(dest.relative_to(ROOT/'public'))
    for solo in job['solos']:
        take=solo['sources'][0]
        solos[take['take']]={'character':character,'masterSha256':take['masterSha256'],'video':video,'offset':solo['offset'],'duration':solo['duration']}
    group=job['choruses'][0]
    chorus['performances'][character]={'character':character,'video':video,'offset':group['offset'],'duration':group['duration']}
    print(character,'correlation',round(correlation,7),'lag',lag,'bytes',dest.stat().st_size)
(ROOT/'src/meeting-room/onboarding-performances.js').write_text('// Generated by scripts/package-onboarding-performances.py from reviewed exact-audio performances.\n'
    +'export const onboardingSolos='+json.dumps(solos,separators=(',',':'))+';\n'
    +'export const onboardingChorus='+json.dumps(chorus,separators=(',',':'))+';\n')
