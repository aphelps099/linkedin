"""Validate exact voice alignment and package the reviewed offline meeting cast."""
import hashlib
import json
import subprocess
from pathlib import Path

import numpy as np
from scipy.io import wavfile
from scipy.signal import correlate, correlation_lags

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / 'assets/meeting-performances/offline-0'
OUT = ROOT / 'public/studio/performances'
TASKS = json.loads((DIR / 'tasks.json').read_text())
assert set(TASKS) == {'strategy', 'guitar', 'accountant', 'keys', 'people'}
hook = json.loads((ROOT / 'src/meeting-room/audio-manifest.json').read_text())['meetings']['offline-0']['cues'][7]
solos = {}
chorus = {'cueDuration': hook['duration'], 'sources': hook['sources'], 'performances': {}}

for character, (task, asset) in TASKS.items():
    path = DIR / f'{character}.json'
    job = json.loads(path.read_text())
    source = DIR / f'{character}-performance.mp4'
    rate, samples = wavfile.read(DIR / job['audio'])
    assert rate == 24000
    x = samples.astype(float)
    data = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source),
                                   '-ac', '1', '-ar', '24000', '-f', 's16le', '-'])
    y = np.frombuffer(data, dtype='<i2').astype(float)
    lag = int(correlation_lags(len(y), len(x))[np.argmax(correlate(y, x))])
    n = min(len(x), len(y))
    correlation = float(np.corrcoef(x[:n], y[:n])[0, 1])
    assert lag == 0 and correlation > .999, (character, lag, correlation)
    # Remove Kevin's baked top margin; retain full head height in all other shots.
    crop = 'crop=888:666:100:38' if character == 'guitar' else 'crop=936:702:76:0'
    dest = OUT / f'{character}-offline-exact-v1.mp4'
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(source), '-vf',
                    f'{crop},scale=720:540,setsar=1', '-c:v', 'libx264', '-preset', 'medium',
                    '-crf', '21', '-g', '24', '-keyint_min', '24', '-sc_threshold', '0',
                    '-bf', '0', '-pix_fmt', 'yuv420p', '-an', '-movflags', '+faststart', str(dest)], check=True)
    job.update(status='reviewed-integrated', taskId=task, assetId=asset, creditsSpent=2,
               runwaySession='5bb35d14-ea57-4d00-979c-8d4c846ccbad', output=source.name,
               outputSha256=hashlib.sha256(source.read_bytes()).hexdigest(),
               runtimeVideo=str(dest.relative_to(ROOT)),
               runtimeSha256=hashlib.sha256(dest.read_bytes()).hexdigest(),
               audioLagSeconds=0, audioWaveformCorrelation=correlation,
               deliveryEncoding={'width': 720, 'height': 540, 'audio': False,
                                 'keyframeIntervalFrames': 24, 'bFrames': 0},
               reviewNotes='Reviewed solo and chorus frames: attached lips, stable headset and identity, subtle eye movement. Live audio retains the approved master. Keys uses the approved separate keyboard detail view during her speaking performance.')
    path.write_text(json.dumps(job, indent=2, ensure_ascii=False) + '\n')
    video = '/' + str(dest.relative_to(ROOT / 'public'))
    for solo in job['solos']:
        take = solo['sources'][0]
        solos[take['take']] = {'character': character, 'masterSha256': take['masterSha256'],
                              'video': video, 'offset': solo['offset'], 'duration': solo['duration']}
    group = job['choruses'][0]
    chorus['performances'][character] = {'character': character, 'video': video,
                                        'offset': group['offset'], 'duration': group['duration']}
    print(character, 'correlation', round(correlation, 7), 'lag', lag, 'bytes', dest.stat().st_size)

(ROOT / 'src/meeting-room/offline-performances.js').write_text(
    '// Generated by scripts/package-offline-performances.py from reviewed exact-audio performances.\n'
    + 'export const offlineSolos=' + json.dumps(solos, separators=(',', ':')) + ';\n'
    + 'export const offlineChorus=' + json.dumps(chorus, separators=(',', ':')) + ';\n')
