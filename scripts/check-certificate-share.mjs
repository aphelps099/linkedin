import assert from 'node:assert/strict';
import express from 'express';
import sharp from 'sharp';
import {certificateName} from '../src/program/components/certificate-art.js';
import {certificateShareUrl,certificateImageUrl,linkedInCertificateUrl,readCertificateName} from '../src/program/components/certificate-share.js';
import {createCertificateShareRouter,renderCertificatePage,renderCertificateImage} from '../server/certificate-share.js';

const name='Zoë & Alex O’Connor';
assert.equal(certificateName('  Alex\n  Morgan\u200b  '),'Alex Morgan');
assert.equal([...certificateName('W'.repeat(90))].length,60);
const url=certificateShareUrl(name,'https://linkedinbeats.com/ignored?other=1#old');
assert.equal(new URL(url).pathname,'/learn/certificate/');
assert.equal(readCertificateName(url),name);
assert.equal(new URL(linkedInCertificateUrl(name)).searchParams.get('url'),url);
assert.equal(new URL(certificateShareUrl('Renée')).searchParams.get('name'),'Renée');
assert.notEqual(certificateImageUrl('Alex'),certificateImageUrl('Sam'));
for(const bad of ['?name=Alex','?v=2','?v=2&name=','?v=2&name=Alex&name=Sam','?v=99&name=Alex','?v=2&name='+ 'x'.repeat(61)])assert.equal(readCertificateName(bad),null);
const hostile='</title><script>alert("x")</script>';
const safe=await renderCertificatePage(hostile);
assert(!safe.includes('<script>'));assert(safe.includes('&lt;script&gt;'));
assert(!safe.includes('textPath'),'seal lettering must survive both browser and server rasterizers');
assert(safe.includes('class="certificate"'));
assert(safe.includes('name="robots" content="noindex, nofollow"'));
const app=express();app.use(createCertificateShareRouter());app.use((_req,res)=>res.status(204).end());
const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
const origin=`http://127.0.0.1:${server.address().port}`;
try{
  const page=await fetch(certificateShareUrl(name,origin));assert.equal(page.status,200);
  assert.equal(page.headers.get('cache-control'),'no-cache');
  assert(page.headers.get('content-security-policy').includes("default-src 'none'"));
  const html=await page.text();
  assert(html.includes(`content="${certificateImageUrl(name).replaceAll('&','&amp;')}"`));
  assert(html.includes('content="1200"'));assert(html.includes('content="630"'));
  assert(html.includes('Zoë &amp; Alex O’Connor'));
  const image=await fetch(certificateImageUrl(name,origin),{headers:{'User-Agent':'LinkedInBot'}});
  assert.equal(image.status,200);assert(image.headers.get('content-type').includes('image/png'));
  const png=Buffer.from(await image.arrayBuffer()),meta=await sharp(png).metadata();
  assert.equal(meta.width,1200);assert.equal(meta.height,630);assert(png.length<5_000_000);
  const dl=await fetch(certificateImageUrl(name,origin)+'&download=1');
  assert(dl.headers.get('content-disposition').includes('attachment'));
  const full=await sharp(Buffer.from(await dl.arrayBuffer())).metadata();assert.equal(full.width,2400);assert.equal(full.height,1700);
  assert.equal((await fetch(certificateShareUrl(name,origin),{method:'HEAD'})).status,200);
  assert.equal((await fetch(origin+'/learn/certificate/?v=2&name=')).status,404);
  assert.equal((await fetch(origin+'/api/learn/certificate.png?v=2&name='+ 'x'.repeat(61))).status,404);
  assert.equal((await fetch(origin+'/learn/')).status,204,'ordinary learner route stays with app');
  assert.equal((await fetch(origin+'/program/')).status,204);
  assert.equal((await renderCertificateImage('W'.repeat(60))).subarray(1,4).toString(),'PNG');
  console.log('Certificate sharing passed: personalized share targets, safe public HTML, crawler-accessible PNG, 1.91:1 full-border preview, full-size download, Unicode/long names, invalid URLs, HEAD and unchanged course routes.');
}finally{server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
